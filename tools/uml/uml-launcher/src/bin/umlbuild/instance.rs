// umlbuild instance — end-to-end orchestrator.
//
// Composes the three lower verbs (kernel, rootfs, image) and emits a
// ready-to-boot Umlfile.toml that umlctl can consume:
//
//   umlbuild instance --profile mvp --out ~/uml-mvp
//   umlctl up -f ~/uml-mvp/Umlfile.toml
//
// The emitted Umlfile is schema_version=1, with kernel.path pinned to
// the just-built linux, an ubd0= append injected so the guest sees the
// rootfs as /dev/ubda, and root=/dev/ubda passed too so init runs from
// the ubd-rooted view (not hostfs).

use anyhow::{Context, Result};
use clap::Args;
use std::path::PathBuf;

use crate::{image, kernel, profile, rootfs};

#[derive(Args, Debug)]
pub struct InstanceArgs {
    /// Profile name or path to a profile TOML.
    #[arg(long, value_name = "NAME_OR_PATH")]
    pub profile: String,

    /// Destination directory; will hold linux, rootfs.img, Umlfile.toml.
    #[arg(long, value_name = "DIR")]
    pub out: PathBuf,

    /// Kernel source root (forwarded to `umlbuild kernel`).
    #[arg(long, value_name = "PATH")]
    pub source: Option<PathBuf>,

    /// Force rebuild of every stage.
    #[arg(long)]
    pub force: bool,
}

pub fn run(args: InstanceArgs) -> Result<()> {
    let prof = profile::resolve(&args.profile)?;
    std::fs::create_dir_all(&args.out).with_context(|| format!("create {}", args.out.display()))?;

    let kernel_out = args.out.join("linux");
    let rootfs_dir = args.out.join("rootfs.d");
    let image_out = args.out.join("rootfs.img");
    let umlfile_out = args.out.join("Umlfile.toml");

    tracing::info!("instance: 1/4 kernel");
    kernel::run(kernel::KernelArgs {
        profile: args.profile.clone(),
        source: args.source.clone(),
        out: Some(kernel_out.clone()),
        jobs: None,
        force: args.force,
    })
    .context("umlbuild instance: kernel stage")?;

    tracing::info!("instance: 2/4 rootfs");
    // `instance` is the orchestrator; always pass --force at the rootfs
    // stage so a re-run picks up profile changes.  If the user wants
    // truly cache-only behavior they should call `umlbuild rootfs`
    // directly.
    rootfs::run(rootfs::RootfsArgs {
        profile: args.profile.clone(),
        out: Some(rootfs_dir.clone()),
        force: true,
    })
    .context("umlbuild instance: rootfs stage")?;

    tracing::info!("instance: 3/4 image");
    image::run(image::ImageArgs {
        rootfs_dir: rootfs_dir.clone(),
        out: image_out.clone(),
        size: prof.image.size.clone(),
        fstype: prof.image.fstype.clone(),
        label: prof.image.label.clone(),
        no_fsck: false,
    })
    .context("umlbuild instance: image stage")?;

    tracing::info!("instance: 4/4 Umlfile");
    let umlfile = render_umlfile(&prof, &kernel_out, &image_out);
    std::fs::write(&umlfile_out, &umlfile)
        .with_context(|| format!("write {}", umlfile_out.display()))?;

    eprintln!(
        "\numlbuild instance: ready\n  kernel:  {}\n  image:   {}\n  Umlfile: {}\n\n\
         next step:\n  umlctl up -f {}",
        kernel_out.display(),
        image_out.display(),
        umlfile_out.display(),
        umlfile_out.display(),
    );
    Ok(())
}

/// Render the Umlfile.toml that points at the freshly-built artifacts.
///
/// We pass the rootfs image to the guest as ubd0 and tell the kernel to
/// root from /dev/ubda — that's how we boot from the ubd image, not
/// from hostfs.  sandbox.cmd= is forwarded on the kernel cmdline for
/// the umlbuild-generated /sbin/init to pick up.
fn render_umlfile(
    prof: &profile::Profile,
    kernel_path: &std::path::Path,
    image_path: &std::path::Path,
) -> String {
    // The sandbox command is baked into /etc/sandbox.cmd inside the
    // rootfs at build time; no need to pass it on the kernel cmdline.
    // To run a different command without rebuilding, mount the image
    // and overwrite /etc/sandbox.cmd, or pass sandbox.cmdfile=/etc/foo
    // on the cmdline.
    let append: Vec<String> = vec![
        format!("ubd0={}", image_path.display()),
        "root=/dev/ubda".to_string(),
        "rw".to_string(),
        "con=null,fd:1".to_string(),
    ];

    let append_toml = append
        .iter()
        .map(|s| format!("    {:?}", s))
        .collect::<Vec<_>>()
        .join(",\n");

    let instance_name = format!("umlbuild-{}", prof.profile.name);
    format!(
        "# Generated by `umlbuild instance --profile {profile_name}`.\n\
         # Do not hand-edit; re-run umlbuild instance to regenerate.\n\
         schema_version = 1\n\
         \n\
         [instance]\n\
         name = \"{instance_name}\"\n\
         labels = {{ builder = \"umlbuild\", profile = \"{profile_name}\" }}\n\
         \n\
         [kernel]\n\
         path    = \"{kernel}\"\n\
         backend = \"{backend}\"\n\
         append  = [\n{append}\n]\n\
         \n\
         [runtime]\n\
         mem   = \"{mem}\"\n\
         ncpus = {ncpus}\n\
         # \"ubd\" tells umlctl to NOT add rootfstype=hostfs and to NOT\n\
         # synthesize an init.sh — the rootfs image ships its own\n\
         # /sbin/init, the kernel boots from /dev/ubda.\n\
         root  = \"ubd\"\n\
         \n\
         [network]\n\
         mode = \"none\"\n",
        profile_name = prof.profile.name,
        kernel = kernel_path.display(),
        backend = prof.instance.backend,
        append = append_toml,
        mem = prof.instance.mem,
        ncpus = prof.instance.ncpus,
    )
}
